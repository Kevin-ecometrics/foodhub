-- Lee app_metadata.role directo del JWT (sin consultar public.users -> sin recursion RLS)
create or replace function public.current_role()
returns text
language sql
stable
set search_path = ''
as $function$
  select coalesce((auth.jwt() -> 'app_metadata' ->> 'role'), '');
$function$;

