-- tables
create table if not exists public.tables (
  id integer generated by default as identity primary key,
  number integer,
  status character varying default 'available'::character varying,
  capacity integer not null,
  location character varying,
  created_at timestamp with time zone not null default timezone('utc'::text, now()),
  updated_at timestamp with time zone not null default timezone('utc'::text, now())
);

-- products
create table if not exists public.products (
  id integer generated by default as identity primary key,
  name character varying not null,
  description text,
  price integer not null,
  category character varying not null,
  image_url character varying,
  is_available boolean default true,
  preparation_time integer,
  meal_type text not null default 'both'::text check (meal_type in ('breakfast', 'lunch', 'both')),
  created_at timestamp with time zone not null default timezone('utc'::text, now()),
  updated_at timestamp with time zone not null default timezone('utc'::text, now()),
  rating numeric default 0.0,
  rating_count integer default 0,
  is_favorite boolean default false,
  extras jsonb default '[]'::jsonb
);

-- orders
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  table_id integer not null references public.tables(id),
  customer_name character varying,
  status character varying default 'active'::character varying,
  total_amount numeric default 0,
  created_at timestamp with time zone not null default timezone('utc'::text, now()),
  updated_at timestamp with time zone not null default timezone('utc'::text, now())
);

-- order_items
create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id integer not null references public.products(id),
  product_name character varying not null,
  price numeric not null,
  quantity integer default 1,
  notes text,
  status character varying default 'ordered'::character varying,
  created_at timestamp with time zone not null default timezone('utc'::text, now()),
  updated_at timestamp with time zone not null default timezone('utc'::text, now()),
  cancelled_quantity integer default 0,
  course smallint not null default 1 check (course >= 1 and course <= 3)
);

-- waiter_notifications
create table if not exists public.waiter_notifications (
  id uuid primary key default gen_random_uuid(),
  table_id integer not null references public.tables(id),
  order_id uuid references public.orders(id),
  type character varying not null,
  message text not null,
  status character varying default 'pending'::character varying,
  created_at timestamp with time zone not null default timezone('utc'::text, now()),
  updated_at timestamp with time zone default timezone('utc'::text, now()),
  payment_method character varying,
  tip_amount numeric default 0
);

-- sales_history
create table if not exists public.sales_history (
  id uuid primary key default gen_random_uuid(),
  table_id integer not null references public.tables(id),
  table_number integer not null,
  customer_name character varying,
  total_amount numeric not null default 0,
  order_count integer not null default 0,
  item_count integer not null default 0,
  created_at timestamp with time zone not null default timezone('utc'::text, now()),
  closed_at timestamp with time zone not null default timezone('utc'::text, now()),
  payment_method character varying
);

-- sales_items
create table if not exists public.sales_items (
  id uuid primary key default gen_random_uuid(),
  sale_id uuid not null references public.sales_history(id) on delete cascade,
  product_name character varying not null,
  price numeric not null,
  quantity integer not null default 1,
  subtotal numeric not null,
  notes text
);

-- customer_feedback
create table if not exists public.customer_feedback (
  id uuid primary key default gen_random_uuid(),
  table_id text not null,
  customer_name text not null,
  rating integer not null check (rating >= 1 and rating <= 5),
  comment text,
  order_count integer not null,
  total_amount numeric not null,
  created_at timestamp with time zone default now()
);

-- tips
create table if not exists public.tips (
  id uuid primary key default gen_random_uuid(),
  order_id uuid,
  table_id integer not null references public.tables(id) on delete cascade,
  customer_name text not null,
  amount numeric not null default 0,
  payment_method text,
  created_at timestamp with time zone not null default now()
);

-- users: cuentas de staff (admin / waiter / super_admin) vinculadas a auth.users.
-- El rol de autorizacion vive en auth.users.raw_app_meta_data (JWT app_metadata),
-- no en esta tabla, para permitir checks de rol sin round-trip a public.users.
create table if not exists public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  name text not null,
  role text not null check (role in ('super_admin', 'admin', 'waiter')),
  pin_code char(4),
  is_active boolean not null default true,
  created_at timestamp with time zone not null default timezone('utc'::text, now()),
  updated_at timestamp with time zone not null default timezone('utc'::text, now()),
  constraint users_pin_code_format check (pin_code is null or pin_code ~ '^[0-9]{4}$')
);

-- app_settings: feature flags opt-in/opt-out configurables desde el admin panel
-- Soporta boolean (toggles) y text (time, select).
-- Lectura publica (el customer sin login necesita leer los flags),
-- escritura solo admin/super_admin.
create table if not exists public.app_settings (
  key text primary key,
  value text not null default 'false',
  updated_at timestamp with time zone not null default timezone('utc', now())
);

